using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;
using DotNetCodeQualityPack.Services;

namespace DotNetCodeQualityPack.Rules
{
    internal enum TeamBlockStatus
    {
        NothingToApply,
        NotApplied,
        UpToDate,
        Outdated,
    }

    /// <summary>
    /// Writes the severity overrides and settings from the Markdown rules file into a marked block at the end of the
    /// solution's .editorconfig. It goes last on purpose: in .editorconfig, later sections win, so team rules override
    /// both the Code Quality Pack defaults and anything above them.
    /// </summary>
    internal static class TeamEditorConfig
    {
        public const string BeginMarker = "# >>> Team rules";
        public const string EndMarker = "# <<< Team rules";

        private static readonly Encoding Utf8NoBom = new UTF8Encoding(false);

        private static readonly Regex Block = new Regex(
            @"(\r?\n)?" + Regex.Escape(BeginMarker) + @".*?" + Regex.Escape(EndMarker) + @"[^\r\n]*(\r?\n)?",
            RegexOptions.Singleline);

        /// <summary>The block for this rules file, or null when it has nothing for .editorconfig.</summary>
        public static string BuildBlock(RulesDocument rules)
        {
            if (rules == null || (rules.Overrides.Count == 0 && rules.Settings.Count == 0))
            {
                return null;
            }

            var sb = new StringBuilder();
            sb.Append("\r\n");
            sb.Append(BeginMarker).Append(" from ").Append(Path.GetFileName(rules.FilePath)).Append("\r\n");
            sb.Append("# Generated by the .NET Code Quality Pack from the Markdown rules file. Edit the .md file, then click Apply again.\r\n");
            sb.Append("[*.cs]\r\n");

            foreach (SeverityOverride o in rules.Overrides)
            {
                if (!string.IsNullOrWhiteSpace(o.Note))
                {
                    sb.Append("# ").Append(o.RuleId).Append(": ").Append(OneLine(o.Note)).Append("\r\n");
                }

                sb.Append("dotnet_diagnostic.").Append(o.RuleId).Append(".severity = ").Append(o.Severity).Append("\r\n");
            }

            foreach (EditorConfigSetting s in rules.Settings)
            {
                if (!string.IsNullOrWhiteSpace(s.Note))
                {
                    sb.Append("# ").Append(s.Key).Append(": ").Append(OneLine(s.Note)).Append("\r\n");
                }

                sb.Append(s.Key).Append(" = ").Append(OneLine(s.Value)).Append("\r\n");
            }

            sb.Append(EndMarker).Append("\r\n");
            return sb.ToString();
        }

        public static TeamBlockStatus GetStatus(string solutionDirectory, RulesDocument rules)
        {
            string block = BuildBlock(rules);
            if (block == null)
            {
                return TeamBlockStatus.NothingToApply;
            }

            string path = Path.Combine(solutionDirectory, SolutionConfigurator.EditorConfigFileName);
            if (!File.Exists(path))
            {
                return TeamBlockStatus.NotApplied;
            }

            Match existing = Block.Match(File.ReadAllText(path));
            if (!existing.Success)
            {
                return TeamBlockStatus.NotApplied;
            }

            return Normalize(existing.Value) == Normalize(block) ? TeamBlockStatus.UpToDate : TeamBlockStatus.Outdated;
        }

        /// <summary>Writes (or rewrites) the block. Returns false when there was nothing to write.</summary>
        public static bool Write(string solutionDirectory, RulesDocument rules, List<string> log)
        {
            string block = BuildBlock(rules);
            if (block == null)
            {
                log.Add("The rules file has no severity overrides or settings, so .editorconfig wasn't changed.");
                return false;
            }

            string path = Path.Combine(solutionDirectory, SolutionConfigurator.EditorConfigFileName);
            bool exists = File.Exists(path);
            string existing = exists ? File.ReadAllText(path) : string.Empty;
            bool hadBlock = Block.IsMatch(existing);

            string rest = (hadBlock ? Block.Replace(existing, "\r\n") : existing).TrimEnd('\r', '\n');
            string content = rest.Length > 0 ? rest + "\r\n" + block : block.TrimStart('\r', '\n');

            if (exists && !hadBlock)
            {
                string backup = path + ".bak-" + DateTime.Now.ToString("yyyyMMdd-HHmmss");
                File.Copy(path, backup);
                log.Add("Backed up .editorconfig to " + Path.GetFileName(backup) + ".");
            }

            File.WriteAllText(path, content, Utf8NoBom);
            log.Add(string.Format(
                "{0} .editorconfig with {1} severity override(s) and {2} setting(s) from {3}.",
                hadBlock ? "Updated" : exists ? "Added team rules to" : "Created",
                rules.Overrides.Count,
                rules.Settings.Count,
                Path.GetFileName(rules.FilePath)));
            return true;
        }

        public static bool Remove(string solutionDirectory, List<string> log)
        {
            string path = Path.Combine(solutionDirectory, SolutionConfigurator.EditorConfigFileName);
            if (!File.Exists(path))
            {
                return false;
            }

            string original = File.ReadAllText(path);
            if (!Block.IsMatch(original))
            {
                log.Add(".editorconfig has no team rules block.");
                return false;
            }

            string text = Block.Replace(original, "\r\n").Trim('\r', '\n');
            if (text.Trim().Length == 0)
            {
                File.Delete(path);
                log.Add("Removed .editorconfig (it only contained the team rules).");
            }
            else
            {
                File.WriteAllText(path, text + "\r\n", Utf8NoBom);
                log.Add("Removed the team rules block from .editorconfig.");
            }

            return true;
        }

        private static string Normalize(string text)
        {
            return text.Replace("\r\n", "\n").Trim();
        }

        private static string OneLine(string text)
        {
            return text.Replace("\r", " ").Replace("\n", " ").Trim();
        }
    }
}
